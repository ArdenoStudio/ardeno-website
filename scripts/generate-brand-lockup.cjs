// Usage: node scripts/generate-brand-lockup.cjs
// Reads the official horizontal lockup master (public/brand/ardeno-lockup-primary.svg) and writes its outlines,
// positions and proportions to components/Website/brandLockup.ts, so the header logo follows the brand guidelines exactly
// (symbol height matches the wordmark's visible height, gap of 0.32 times the symbol height, natural letter spacing).
const fs = require('fs');
const path = require('path');

const source = path.join(__dirname, '..', 'public', 'brand', 'ardeno-lockup-primary.svg');
const target = path.join(__dirname, '..', 'components', 'Website', 'brandLockup.ts');
const svg = fs.readFileSync(source, 'utf8');

const viewBox = svg.match(/viewBox="([^"]+)"/)[1].split(/\s+/).map(Number);
const paths = [...svg.matchAll(/<path fill="([^"]+)" d="([^"]+)" transform="([^"]+)"\s*\/>/g)].map(m => ({ fill: m[1], d: m[2], transform: m[3] }));
if (paths.length !== 7) throw new Error(`expected the mark and six letters, found ${paths.length} paths`);

const [mark, ...glyphs] = paths;
// The mark occupies the first 116 units (8 of padding, the A, then padding before the gap); the wordmark follows.
const MARK_BOX = 116;

const out = `// Generated by scripts/generate-brand-lockup.cjs from public/brand/ardeno-lockup-primary.svg. Do not edit by hand.
export const LOCKUP = {
  width: ${viewBox[2]},
  height: ${viewBox[3]},
  markBox: ${MARK_BOX},
  mark: { d: ${JSON.stringify(mark.d)}, transform: ${JSON.stringify(mark.transform)} },
  glyphs: ${JSON.stringify(glyphs.map(g => ({ d: g.d, transform: g.transform })), null, 4).replace(/\n/g, '\n  ')},
} as const;
`;
fs.writeFileSync(target, out);
console.log(`wrote ${path.relative(process.cwd(), target)}: viewBox ${viewBox.join(' ')}, ${glyphs.length} letters`);
